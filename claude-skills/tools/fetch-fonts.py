#!/usr/bin/env python3
"""Download Google Fonts (arabic + latin subsets) into a skill's templates/fonts/ with a local fonts.css.
usage: python fetch-fonts.py <out_dir> "family=Readex+Pro:wght@400;600;800" ["family=..."]
All Google Fonts used here are under the SIL Open Font License, so they can be bundled."""
import os, re, sys, urllib.request
out = sys.argv[1]; os.makedirs(out, exist_ok=True)
url = 'https://fonts.googleapis.com/css2?' + '&'.join(sys.argv[2:]) + '&display=block'
UA = {'User-Agent': 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 Chrome/120 Safari/537.36'}
css = urllib.request.urlopen(urllib.request.Request(url, headers=UA)).read().decode()
blocks = re.findall(r'/\* ([\w-]+) \*/\s*(@font-face \{.*?\})', css, re.S)
keep = []
for subset, b in blocks:
    if subset not in ('arabic', 'latin', 'latin-ext'): continue
    fam = re.search(r"font-family: '([^']+)'", b).group(1).replace(' ', '')
    w = re.search(r'font-weight: ([\d ]+);', b).group(1).replace(' ', '-')
    src = re.search(r'url\((https://[^)]+)\)', b).group(1)
    name = f'{fam}-{w}-{subset}.woff2'
    p = os.path.join(out, name)
    if not os.path.exists(p):
        with open(p, 'wb') as f: f.write(urllib.request.urlopen(urllib.request.Request(src, headers=UA)).read())
    keep.append(f'/* {subset} */\n' + b.replace(src, name))
open(os.path.join(out, 'fonts.css'), 'w').write('/* Local copies of Google Fonts (SIL OFL). Generated by tools/fetch-fonts.py */\n' + '\n'.join(keep) + '\n')
print(len(keep), 'faces ->', out)
