def brain_fill(field: str, goal: str, d: dict) -> list[dict]:
    """يملأ العقل من بروفايل المجال (الخانات الفارغة فقط، فما كتبه العميل لا يُمسح). يرجع ملاحظات المعرفة الجديدة."""
    p = FIELDS.get(field)
    g = GOAL_BY.get(goal) or GOAL_BY.get((p or {}).get("goal") or "") or GOALS[0]
    empty = lambda k: not str(d.get(k) or "").strip()  # noqa: E731
    if empty("cta"):
        d["cta"] = g[2]
    d["goal"] = g[0]
    if not p:
        return []
    for k, v in (("domain", p["name"]), ("audience", p["audience"]), ("rules", p["rules"])):
        if empty(k):
            d[k] = v
    if not d.get("type_set"):
        d.update(type=p["type"], type_set=True)
    d["field"] = field
    notes = d.setdefault("notes", [])
    have = {n.get("quiz") for n in notes}
    new = []
    for qid, section, title, body in (("voice", "voice", "نبرة العلامة", p["voice"]), ("field_words", "other", "كلمات المجال", p["words"]),
                                      ("field_angles", "other", "أنواع المحتوى في المجال", p["angles"]), ("field_goal", "offers", "هدف المحتوى", g[1])):
        if qid in have:
            continue
        n = {"id": uuid.uuid4().hex[:10], "quiz": qid, "section": section, "title": title, "source": "field", "body": body, "summary": body[:300]}
        notes.append(n)
        new.append(n)
    return new


def month_items(field: str, start, days: int, time_: str, cta: str, ok_tpl) -> list[dict]:
    """خطة شهر جاهزة للمجال (مسودة): منشور في اليوم من أفكار المجال، بخلطة ريل بالقالب / كاروسيل / تصوير بالجوال."""
    from datetime import timedelta  # noqa: PLC0415
    p = FIELDS.get(field)
    if not p:
        return []
    reels = [t for t in p["reels"] if ok_tpl(t)] or []
    ideas = p["ideas"]
    out = []
    for i in range(days):
        it = ideas[i % len(ideas)]
        slot = i % 3
        if slot == 0 and reels:
            tpl, kind, name = reels[(i // 3) % len(reels)], "reel", "ريل بقالب"
        elif slot == 1:
            tpl, kind, name = "carousel", "carousel", "كاروسيل"
        else:
            tpl, kind, name = "phone", "phone", "تصوير بالجوال"
        out.append({"id": uuid.uuid4().hex[:8], "date": (start + timedelta(days=i)).isoformat(), "time": time_, "tpl": tpl, "kind": kind,
                    "tpl_name": name, "bucket": it["title"], "title": it["title"], "idea": it["idea"], "hook": it["hook"], "cta": cta,
                    "why": "من خطة المجال الجاهزة", "aud": ""})
    return out
