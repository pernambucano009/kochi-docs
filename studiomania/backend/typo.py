    import random

    r = random.Random(seed)
    has = bool((person or {}).get("present"))
    col = COLLECTIONS.get(collection or "") or COLLECTIONS[pick_collection(None, r)]
    weights = {k: v for k, v in col["kinds"].items() if has or k not in PERSON_KINDS}
